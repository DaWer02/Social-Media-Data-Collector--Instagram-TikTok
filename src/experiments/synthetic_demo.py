def create_demo_multipost_dataset(output_path: Path | None = None) -> Path:
    """Create and save a multi-post demo annotated CSV dataset for experiments.

    Args:
        output_path: Optional destination path. Defaults to data/annotated/comments_labeled_demo.csv.

    Returns:
        Path: Path to the generated demo CSV file.
    """
    ensure_directories()
    dest = Path(output_path or (ANNOTATED_DATA_DIR / "comments_labeled_demo.csv")).resolve()
    dest.parent.mkdir(parents=True, exist_ok=True)

    with open(dest, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=DEMO_FIELDNAMES)
        writer.writeheader()
        writer.writerows(DEMO_COMMENTS)

    return dest
